#!/usr/bin/env node
//
// Publish-pipeline helper: compute SHA-256 of each built release asset and
// write/update both checksum manifests that the install paths verify against:
//
//   - npm/checksums.json   { "<version>": { "<asset>": "<sha256hex>" } }
//   - scripts/SHA256SUMS   lines: "<sha256hex>  <asset>"
//
// Version is read from npm/package.json. Run this BEFORE publishing so the
// install paths (postinstall, self-install, install.sh, install.ps1) can
// fail-closed on tampering.
//
// Usage: node scripts/build/write-checksums.cjs <assets-dir>

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const repoRoot = path.resolve(__dirname, "..", "..");
const checksumsJsonPath = path.join(repoRoot, "npm", "checksums.json");
const sha256sumsPath = path.join(repoRoot, "scripts", "SHA256SUMS");
const packageJsonPath = path.join(repoRoot, "npm", "package.json");

function sha256OfFile(filePath) {
  const hash = crypto.createHash("sha256");
  hash.update(fs.readFileSync(filePath));
  return hash.digest("hex");
}

function main() {
  const assetsDir = process.argv[2];
  if (!assetsDir) {
    console.error("Usage: node scripts/build/write-checksums.cjs <assets-dir>");
    process.exit(1);
  }

  const resolvedAssetsDir = path.resolve(assetsDir);
  const stat = fs.statSync(resolvedAssetsDir);
  if (!stat.isDirectory()) {
    console.error(`Not a directory: ${resolvedAssetsDir}`);
    process.exit(1);
  }

  const pkg = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
  const version = String(pkg.version).replace(/^v/, "");

  const entries = fs
    .readdirSync(resolvedAssetsDir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => name !== "SHA256SUMS" && !name.endsWith(".minisig") && !name.endsWith(".sig"))
    .sort();

  if (entries.length === 0) {
    console.error(`No asset files found in ${resolvedAssetsDir}`);
    process.exit(1);
  }

  const hashes = {};
  for (const name of entries) {
    hashes[name] = sha256OfFile(path.join(resolvedAssetsDir, name));
  }

  // Update npm/checksums.json (merge: replace this version's block).
  let manifest = {};
  try {
    manifest = JSON.parse(fs.readFileSync(checksumsJsonPath, "utf8")) || {};
  } catch {
    manifest = {};
  }
  manifest[version] = hashes;
  fs.writeFileSync(checksumsJsonPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

  // Write scripts/SHA256SUMS (sha256sum-compatible: "<hash>  <asset>").
  const header =
    "# Gordon CLI release-asset SHA-256 checksums.\n" +
    "# Generated by scripts/build/write-checksums.cjs — do not hand-edit.\n" +
    `# version: ${version}\n`;
  const body = entries.map((name) => `${hashes[name]}  ${name}`).join("\n");
  fs.writeFileSync(sha256sumsPath, `${header}${body}\n`, "utf8");

  console.log(`Wrote ${entries.length} checksum(s) for v${version}:`);
  for (const name of entries) {
    console.log(`  ${hashes[name]}  ${name}`);
  }
  console.log(`Updated ${path.relative(repoRoot, checksumsJsonPath)} and ${path.relative(repoRoot, sha256sumsPath)}`);
}

main();
