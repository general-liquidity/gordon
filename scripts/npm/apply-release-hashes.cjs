#!/usr/bin/env node
/**
 * Deterministically wire per-asset sha256 hashes + version into the
 * direct-binary distribution manifests:
 *
 *   - Formula/gordon.rb        (Homebrew)
 *   - scripts/scoop/gordon.json (Scoop)
 *   - scripts/SHA256SUMS        (install.sh / install.ps1 integrity)
 *
 * Replaces the fragile ordered-`sed` block that lived in release.yml, which
 * relied on the Formula's sha256 lines appearing in a fixed source order and
 * reused the x64 hash for the Scoop arm64 entry. Here every hash is keyed by
 * ASSET NAME (from the staging manifest), so order and per-arch correctness are
 * guaranteed regardless of how the file is arranged.
 *
 * Usage:
 *   node scripts/npm/apply-release-hashes.cjs --manifest staging/manifest.json --version 0.1.0
 * Optional --output-root writes rehearsal copies instead of production files.
 *
 * The manifest is produced by scripts/npm/stage-platform-packages.cjs and maps
 * each staged asset to its sha256.
 */

const fs = require("node:fs");
const path = require("node:path");

const defaultRepoRoot = path.resolve(__dirname, "..", "..");

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--manifest") out.manifest = argv[++i];
    else if (argv[i] === "--version") out.version = argv[++i];
    else if (argv[i] === "--output-root") out.outputRoot = argv[++i];
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.manifest) {
    console.error(
      "Usage: node scripts/npm/apply-release-hashes.cjs --manifest <file> [--version <v>] [--output-root <dir>]",
    );
    process.exit(1);
  }

  const manifest = JSON.parse(fs.readFileSync(path.resolve(args.manifest), "utf8"));
  const version = String(args.version || manifest.version).replace(/^v/, "");
  const repoRoot = args.outputRoot ? path.resolve(args.outputRoot) : defaultRepoRoot;

  // asset name -> sha256
  const hashByAsset = new Map();
  for (const item of manifest.staged || []) {
    hashByAsset.set(item.asset, item.sha256);
  }

  const missing = [];
  const hashFor = (asset) => {
    const h = hashByAsset.get(asset);
    if (!h) missing.push(asset);
    return h;
  };

  // ---- Formula/gordon.rb --------------------------------------------------
  const formulaPath = path.join(repoRoot, "Formula", "gordon.rb");
  const formula = fs.readFileSync(formulaPath, "utf8").split("\n");
  let pendingAsset = null;
  const urlAssetRe = /url\s+".*\/(gordon-[a-z0-9-]+(?:\.exe)?)"/i;
  for (let i = 0; i < formula.length; i += 1) {
    const line = formula[i];
    const versionMatch = line.match(/^(\s*version\s+)"[^"]*"(.*)$/);
    if (versionMatch) {
      formula[i] = `${versionMatch[1]}"${version}"${versionMatch[2]}`;
      continue;
    }
    const urlMatch = line.match(urlAssetRe);
    if (urlMatch) {
      pendingAsset = urlMatch[1];
      continue;
    }
    const shaMatch = line.match(/^(\s*sha256\s+)"[^"]*"(.*)$/);
    if (shaMatch && pendingAsset) {
      const h = hashFor(pendingAsset);
      if (h) formula[i] = `${shaMatch[1]}"${h}"${shaMatch[2]}`;
      pendingAsset = null;
    }
  }
  fs.writeFileSync(formulaPath, formula.join("\n"), "utf8");

  // ---- scripts/scoop/gordon.json -----------------------------------------
  const scoopPath = path.join(repoRoot, "scripts", "scoop", "gordon.json");
  const scoop = JSON.parse(fs.readFileSync(scoopPath, "utf8"));
  scoop.version = version;

  const setArch = (archKey, asset) => {
    const arch = scoop.architecture?.[archKey];
    if (!arch) return;
    const h = hashFor(asset);
    if (h) arch.hash = h;
    arch.url = `https://github.com/general-liquidity/gordon/releases/download/v${version}/${asset}`;
    const auto = scoop.autoupdate?.architecture?.[archKey];
    if (auto) {
      auto.url = `https://github.com/general-liquidity/gordon/releases/download/v${version}/${asset}`;
    }
  };
  setArch("64bit", "gordon-windows-x64.exe");
  setArch("arm64", "gordon-windows-arm64.exe");
  fs.writeFileSync(scoopPath, `${JSON.stringify(scoop, null, 2)}\n`, "utf8");

  // ---- scripts/SHA256SUMS -------------------------------------------------
  const sumsPath = path.join(repoRoot, "scripts", "SHA256SUMS");
  const header =
    "# Gordon CLI release-asset SHA-256 checksums.\n" +
    "# Generated by scripts/npm/apply-release-hashes.cjs — do not hand-edit.\n" +
    `# version: ${version}\n`;
  const body = (manifest.staged || []).map((item) => `${item.sha256}  ${item.asset}`).join("\n");
  fs.writeFileSync(sumsPath, `${header}${body}\n`, "utf8");

  console.log(`Applied release hashes for v${version} to Formula, Scoop, and SHA256SUMS.`);
  if (missing.length > 0) {
    // Non-fatal: a skipped target (e.g. win32-arm64) leaves its manifest entry
    // untouched rather than reusing another arch's hash. Surface it loudly.
    console.warn(`Warning: no staged hash for: ${missing.join(", ")} (left unchanged).`);
  }
}

main();
