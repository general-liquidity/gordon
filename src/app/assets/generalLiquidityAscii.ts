function trimToContent(lines: string[]): string[] {
  let minIndex = Number.POSITIVE_INFINITY;
  let maxIndex = 0;
  for (const line of lines) {
    const first = line.search(/\S/u);
    if (first === -1) {
      continue;
    }
    const last = line.length - 1 - [...line].reverse().findIndex((character) => /\S/u.test(character));
    minIndex = Math.min(minIndex, first);
    maxIndex = Math.max(maxIndex, last);
  }
  if (!Number.isFinite(minIndex)) {
    return lines;
  }
  return lines.map((line) => line.slice(minIndex, maxIndex + 1));
}

