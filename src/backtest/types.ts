// ============================================================================
// OHLC Data
// ============================================================================

/**
 * OHLC (Open-High-Low-Close) candlestick data.
 * This is the basic price data structure used in backtesting.
 */
export interface OHLC {
  /** Candle open time (Unix timestamp in milliseconds) */
  timestamp: number;

  /** Opening price */
  open: number;

  /** Highest price during the candle period */
  high: number;

  /** Lowest price during the candle period */
  low: number;

  /** Closing price */
  close: number;

  /** Trading volume */
  volume: number;
}

// ============================================================================
// Signals
// ============================================================================

/**
 * Signal type enumeration.
 */
export type SignalType = "BUY" | "SELL" | "HOLD";

/**
 * Trading signal generated by a strategy.
 */
export interface Signal {
  /** Type of signal */
  type: SignalType;

  /** Price at which the signal was generated */
  price: number;

  /** Unix timestamp when the signal was generated */
  timestamp: number;

  /** Human-readable explanation for the signal */
  reason: string;

  /** Grid level index (0-based) for grid/DCA strategies. When set, the engine allows multiple concurrent positions. */
  gridLevel?: number;

  /** Maximum simultaneous grid positions allowed. Only used when gridLevel is set. Defaults to 1. */
  maxPositions?: number;
}

