export interface BacktestConfig {
  /** Strategy ID */
  strategyId: string;

  /** Trading pair (e.g., "BTCUSDT") */
  symbol: string;

  /** Timeframe for candles (e.g., "4h", "1h", "15m") */
  timeframe: string;

  /** Number of days to backtest */
  days: number;

  /** Initial capital in USDT */
  initialCapital: number;

  /** Position size as percentage of capital (0-100) */
  positionSizePercent: number;

  /** Whether to compound profits */
  compounding: boolean;

  /** Trading fees percentage (e.g., 0.1 for 0.1%) */
  feePercent: number;

  /** Slippage percentage to simulate (e.g., 0.05 for 0.05%) */
  slippagePercent: number;

  /** Named simulation realism profile */
  simulationProfile?: "baseline" | "realistic" | "conservative";

  /** Execution lag in whole bars */
  executionLagBars?: number;

  /** Half-spread cost in basis points */
  spreadBps?: number;

  /** Additional market-impact cost in basis points */
  marketImpactBps?: number;
}

