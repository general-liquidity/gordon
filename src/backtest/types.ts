/**
 * Strategy interface specifically for the backtest engine.
 * Strategies implement this to generate signals synchronously
 * from pre-calculated indicator values.
 */
export interface Strategy {
  /** Unique strategy identifier */
  id: string;

  /** Human-readable strategy name */
  name: string;

  /**
   * Generate a trading signal based on current bar and indicators.
   *
   * @param bar - Current OHLC bar
   * @param indicators - Pre-calculated indicator values for this bar
   * @param position - Current open position (if any)
   * @returns Trading signal
   */
  generateSignal(
    bar: OHLC,
    indicators: IndicatorState,
    position: Position | null
  ): Signal;

  /**
   * Optional Kelly criterion parameters for position sizing.
   * If provided and positionSizing is KELLY, these will be used.
   */
  kellyParams?: KellyParams;
}
