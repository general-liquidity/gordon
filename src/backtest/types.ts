/**
 * Position sizing mode for determining trade size.
 */
export type PositionSizingMode =
  | "FIXED_AMOUNT" // Use fixed dollar amount
  | "FIXED_PERCENT" // Use percentage of current equity
  | "KELLY" // Kelly criterion (requires win rate/avg win/loss)
  | "ALL_IN"; // Use 95% of available capital

/**
 * Kelly criterion parameters for position sizing.
 */
export interface KellyParams {
  /** Historical win rate (0-1) */
  winRate: number;
  /** Average winning trade return */
  avgWin: number;
  /** Average losing trade return (positive number) */
  avgLoss: number;
  /** Fraction multiplier (default 0.5 for half-Kelly) */
  fractionMultiplier?: number;
}

/**
 * Parameters for configuring a backtest run (engine format).
 */
export interface BacktestParams {
  /** Starting capital for the backtest */
  initialCapital: number;

  /**
   * Bar interval of the series being tested ("1m", "1h", "4h", "1d", ...).
   *
   * Required because it sets the annualization factor for Sharpe, Sortino and
   * volatility. Without it the metrics layer annualized everything at 365, as
   * though every bar were a calendar day, which on the default 4h bars
   * understates Sharpe by sqrt(2190/365) = 2.45x and on 1h bars by 4.9x.
   */
  timeframe: string;

  /** Position sizing mode */
  positionSizing: PositionSizingMode;

  /** Fixed amount to use per trade (for FIXED_AMOUNT mode) */
  fixedAmount?: number;

  /** Percentage of equity to use per trade (for FIXED_PERCENT mode, 0-1) */
  fixedPercent?: number;

  /** Commission rate as decimal (e.g., 0.001 = 0.1%) */
  commissionRate: number;

  /** Slippage rate as decimal (e.g., 0.0005 = 0.05%) */
  slippageRate: number;

  /** Signal execution lag in whole bars */
  executionLagBars?: number;

  /** Half-spread cost as decimal (e.g., 0.0002 = 2 bps) */
  spreadRate?: number;

  /** Additional market-impact cost as decimal */
  marketImpactRate?: number;

  /** Whether to allow short positions */
  allowShorts: boolean;

  /** Maximum drawdown before stopping (as decimal, e.g., 0.25 = 25%) */
  maxDrawdown?: number;

  /** Kelly criterion parameters (required if positionSizing is KELLY) */
  kelly?: KellyParams;
}

