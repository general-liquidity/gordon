export function getSprite(species: Species, frame: number): string[] {
  const spriteSet = SPRITES[species];
  if (!spriteSet) {
    // Fallback for species without custom sprites
    return ["            ", "    [?]     ", "   (   )    ", "    | |     ", "            "];
  }
  return spriteSet[frame % 3]!;
}
